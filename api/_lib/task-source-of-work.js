'use strict';

/*
 * PHF Task — SOURCE OF WORK classifier (Reporting truth, 2026-09-01).
 *
 * LOCKED BUSINESS PRINCIPLE: self-created/self-assigned Tasks are legitimate,
 * but management reporting must NOT present self-created volume as equivalent
 * to work assigned by another person.
 *
 * Classification uses CREATION-TIME truth, NEVER the current active primary:
 *   - creator            = task.tasks.created_by_employee_code (immutable)
 *   - initial primary    = the earliest role='primary' task.assignees row
 *                          (min assigned_at) — retained across every transfer
 *   - proposal linkage   = task.proposal_decisions.generated_task_id
 *   - recurrence linkage = task.tasks.recurring_series_id
 *
 * A later transfer NEVER rewrites the classification.
 *
 * Pure, dependency-free — shared by api/_lib/task-reporting-v2.js (Overview /
 * Báo cáo) and the list/detail "Tự giao" badge (task-core.js / task-read-
 * bridge.js) so every surface agrees.
 */

const SOURCE_OF_WORK_VALUES = Object.freeze(['self_assigned', 'assigned_by_other', 'proposal', 'unknown']);

function norm(value) {
  return String(value == null ? '' : value).trim().toUpperCase();
}

/*
 * classifySourceOfWork({ createdByEmployeeCode, createdByAccountId,
 *                        initialPrimaryEmployeeCode, proposalGenerated,
 *                        recurringSeriesId })
 * -> 'self_assigned' | 'assigned_by_other' | 'proposal' | 'unknown'
 *
 * Precedence:
 *   1. proposal   — the Task was generated by accepting a Proposal
 *                   (proposer != acceptor is guaranteed by DB CHECK). Kept as
 *                   its own value; a 2-way management view may roll it under
 *                   "Được giao" but the contract preserves it.
 *   2. unknown    — no real creator employee code (account-only Admin create,
 *                   legacy import) OR no resolvable initial primary. NEVER
 *                   guessed as self.
 *   3. self_assigned    — creator === initial primary (immutable identities).
 *   4. assigned_by_other — creator !== initial primary.
 *
 * recurringSeriesId is NOT a source value — it is the orthogonal
 * is_recurring_occurrence flag (see isRecurringOccurrence). A recurrence
 * occurrence still resolves self_assigned (rule creator == rule primary) or
 * assigned_by_other (rule creator != rule primary) underneath.
 */
function classifySourceOfWork(input) {
  const row = input || {};
  if (row.proposalGenerated === true) return 'proposal';

  const creator = norm(row.createdByEmployeeCode);
  if (!creator) return 'unknown'; // account-only Admin / legacy import

  const initialPrimary = norm(row.initialPrimaryEmployeeCode);
  if (!initialPrimary) return 'unknown'; // no primary assignee history to compare against

  return creator === initialPrimary ? 'self_assigned' : 'assigned_by_other';
}

function isRecurringOccurrence(input) {
  const row = input || {};
  return !!norm(row.recurringSeriesId);
}

// Convenience for reporting rollups — the management 2-way view.
// "Được giao" = assigned_by_other + proposal; "Tự tạo / tự giao" = self_assigned.
function rollupSourceOfWork(sourceOfWork) {
  if (sourceOfWork === 'self_assigned') return 'self';
  if (sourceOfWork === 'assigned_by_other' || sourceOfWork === 'proposal') return 'assigned';
  return 'unknown';
}

module.exports = {
  SOURCE_OF_WORK_VALUES,
  classifySourceOfWork,
  isRecurringOccurrence,
  rollupSourceOfWork,
};
